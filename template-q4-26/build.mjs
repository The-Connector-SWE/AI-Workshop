// build.mjs — precompile Template Q4-26 into dist/app.min.js.
// Run `npm install` once, then `npm run build` after editing app.jsx, world3d.js,
// visuals.js, i18n.js or ../logos.jsx. Content files (../game-data.jsx, ../data.jsx,
// ../labs-data.js) are plain JavaScript and load directly, so content edits need no build.
import { transform } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";

const here = new URL(".", import.meta.url);
const SOURCES = ["../logos.jsx", "i18n.js", "visuals.js", "world3d.js", "app.jsx"];

const parts = [];
for (const file of SOURCES) {
  const src = await readFile(new URL(file, here), "utf8");
  const { code } = await transform(src, { loader: "jsx", jsx: "transform", jsxFactory: "React.createElement", jsxFragment: "React.Fragment", target: "es2019" });
  // each file keeps its own top-level scope, as separate <script> tags did
  parts.push(`/* ${file} */\n(function () {\n${code}\n})();`);
}
const { code } = await transform(parts.join("\n"), { minify: true, target: "es2019" });
await mkdir(new URL("dist/", here), { recursive: true });
await writeFile(new URL("dist/app.min.js", here), `/* generated by build.mjs — do not edit */\n${code}`);
console.log(`dist/app.min.js  ${(code.length / 1024).toFixed(1)} KB`);
